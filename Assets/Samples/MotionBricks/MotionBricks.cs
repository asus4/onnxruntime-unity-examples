    /// <summary>
    /// One pose of the SOMA skeleton in SOMA model space (Y up, meters, right-handed).
    /// The bone offsets are fixed, so a pose is the hips position plus one rotation per joint.
    /// </summary>
    public sealed class SomaPose
    {
        /// <summary>World position of the hips (joint 0).</summary>
        public float3 RootPosition;

        /// <summary>Joint 0 is the world rotation of the hips. The others are relative to their parent.</summary>
        public readonly quaternion[] LocalRotations = new quaternion[SomaSkeleton.JointCount];

        /// <summary>The idle pose standing at ground (x, z), turned by yaw radians. Yaw 0 faces +Z.</summary>
        public void SetIdle(float2 ground, float yaw)
        {
            Array.Copy(SomaSkeleton.IdleLocalRotations, LocalRotations, SomaSkeleton.JointCount);
            RootPosition = new float3(ground.x, SomaSkeleton.LocalPositions[0].y, ground.y);
            LocalRotations[0] = math.mul(quaternion.RotateY(yaw), LocalRotations[0]);
        }

        public void CopyFrom(SomaPose other)
        {
            RootPosition = other.RootPosition;
            Array.Copy(other.LocalRotations, LocalRotations, SomaSkeleton.JointCount);
        }

        public void Lerp(SomaPose a, SomaPose b, float t)
        {
            RootPosition = math.lerp(a.RootPosition, b.RootPosition, t);
            for (int i = 0; i < SomaSkeleton.JointCount; i++)
            {
                LocalRotations[i] = math.slerp(a.LocalRotations[i], b.LocalRotations[i], t);
            }
        }

        public void ComputeWorld(Span<float3> positions, Span<quaternion> rotations)
        {
            positions[0] = RootPosition;
            rotations[0] = LocalRotations[0];
            for (int i = 1; i < SomaSkeleton.JointCount; i++)
            {
                int p = SomaSkeleton.Parents[i];
                rotations[i] = math.mul(rotations[p], LocalRotations[i]);
                positions[i] = positions[p] + math.mul(rotations[p], SomaSkeleton.LocalPositions[i]);
            }
        }

        /// <summary>Facing around Y, measured from the leg joints like the model does. 0 faces +Z.</summary>
        public float Heading => HeadingFromLegs(
            math.mul(LocalRotations[0], SomaSkeleton.LocalPositions[SomaSkeleton.RightLeg]),
            math.mul(LocalRotations[0], SomaSkeleton.LocalPositions[SomaSkeleton.LeftLeg]));

        public static float HeadingFromLegs(float3 right, float3 left)
        {
            float3 across = new(right.x - left.x, 0, right.z - left.z);
            if (math.lengthsq(across) < 1e-12f)
            {
                return 0;
            }
            float3 forward = math.cross(new float3(0, 1, 0), math.normalize(across));
            return math.atan2(forward.x, forward.z);
        }
    }

    /// <summary>Motion generated by one MotionBricks call, at 30 Hz.</summary>
    public sealed class MotionSegment
    {
        public readonly SomaPose[] Frames = new SomaPose[MotionBricks.MaxFrames];

        /// <summary>Left heel, left toe, right heel and right toe contact, from 0 to 1.</summary>
        public readonly float4[] FootContacts = new float4[MotionBricks.MaxFrames];

        public int FrameCount;
        public double InferenceMilliseconds;

        public MotionSegment()
        {
            for (int i = 0; i < Frames.Length; i++)
            {
                Frames[i] = new SomaPose();
            }
        }
    }

    /// <summary>
    /// MotionBricks SOMA model: generates the motion from four context poses toward one to four
    /// target poses. https://github.com/NVlabs/motionbricks
    ///
    /// The pre and post processing ports the SOMA engine of the original repository
    /// (motionbricks/model/soma/kernels.py).
    /// </summary>
    public sealed class MotionBricks : IDisposable
    {
        public const float SampleRate = 30f;
        public const int MinTokens = 6;
        public const int MaxTokens = 16;
        const int PosesPerToken = 4;
        const int BoundaryFrames = PosesPerToken - 1;
        /// <summary>The most frames one call generates, after removing the boundary frames.</summary>
        public const int MaxFrames = MaxTokens * PosesPerToken - 2 * BoundaryFrames;

        const int Slots = 2 * PosesPerToken; // four context poses, then four target poses
        const int Joints = SomaSkeleton.JointCount;
        const int PoseFeatures = (Joints - 1) * 3 + Joints * 6;
        const int MotionFeatures = 366;
        const int MotionRotationOffset = 5 + (Joints - 1) * 3;

        static readonly string[] InputNames =
        {
            "global_root_values",
            "has_global_root_values",
            "local_root_values",
            "has_local_root_values",
            "local_poses",
            "has_local_poses",
            "allowed_pred_num_tokens",
        };
        static readonly string[] OutputNames = { "pred_global_motions", "pred_num_tokens" };

        readonly SessionOptions sessionOptions;
        readonly InferenceSession session;
        readonly RunOptions runOptions;
        readonly OrtValue[] inputs;
        readonly OrtValue[] outputs;

        readonly float[] globalRootValues = new float[Slots * 5];
        readonly int[] hasGlobalRootValues = new int[Slots];
        readonly float[] localRootValues = new float[Slots * 4];
        readonly int[] hasLocalRootValues = new int[Slots];
        readonly float[] localPoses = new float[Slots * PoseFeatures];
        readonly int[] hasLocalPoses = new int[Slots];
        readonly int[] allowedTokens = new int[MaxTokens - MinTokens + 1];
        readonly float[] motions = new float[MaxTokens * PosesPerToken * MotionFeatures];
        readonly int[] tokenCount = new int[1];

        readonly float3[] slotPositions = new float3[Slots * Joints];
        readonly quaternion[] slotRotations = new quaternion[Slots * Joints];
        readonly quaternion[] frameRotations = new quaternion[Joints];

        public MotionBricks(string modelPath)
        {
            try
            {
                sessionOptions = new SessionOptions();
                // One request at a time. A fixed batch size lets ONNX Runtime fold the shape
                // computations of the attention layers.
                sessionOptions.AddFreeDimensionOverrideByName("batch_size", 1);
                // Loading from a path keeps the weights out of the managed heap.
                session = new InferenceSession(modelPath, sessionOptions);
                runOptions = new RunOptions();
            }
            catch
            {
                session?.Dispose();
                sessionOptions?.Dispose();
                throw;
            }
            session.LogIOInfo();

            inputs = new[]
            {
                OrtValue.CreateTensorValueFromMemory(globalRootValues, new long[] { 1, Slots, 5 }),
                OrtValue.CreateTensorValueFromMemory(hasGlobalRootValues, new long[] { 1, Slots }),
                OrtValue.CreateTensorValueFromMemory(localRootValues, new long[] { 1, Slots, 4 }),
                OrtValue.CreateTensorValueFromMemory(hasLocalRootValues, new long[] { 1, Slots }),
                OrtValue.CreateTensorValueFromMemory(localPoses, new long[] { 1, Slots, PoseFeatures }),
                OrtValue.CreateTensorValueFromMemory(hasLocalPoses, new long[] { 1, Slots }),
                OrtValue.CreateTensorValueFromMemory(allowedTokens, new long[] { 1, allowedTokens.Length }),
            };
            outputs = new[]
            {
                OrtValue.CreateTensorValueFromMemory(motions, new long[] { 1, MaxTokens * PosesPerToken, MotionFeatures }),
                OrtValue.CreateTensorValueFromMemory(tokenCount, new long[] { 1 }),
            };
        }

        public void Dispose()
        {
            foreach (var value in inputs)
            {
                value.Dispose();
            }
            foreach (var value in outputs)
            {
                value.Dispose();
            }
            runOptions?.Dispose();
            session?.Dispose();
            sessionOptions?.Dispose();
        }

        /// <summary>
        /// Generates the motion from the last context pose toward the targets. Call from one thread at a time.
        /// </summary>
        /// <param name="context">The four latest poses at 30 Hz, oldest first.</param>
        /// <param name="targets">One to four target poses at 30 Hz.</param>
        /// <param name="targetHasPose">
        /// True: reach the targets' body pose, and end exactly on the first target.
        /// False: only reach the targets' position, heading and velocity; the model chooses the body pose.
        /// </param>
        /// <param name="minTokens">Fewest tokens (four frames each) the model may generate.</param>
        /// <param name="maxTokens">Most tokens the model may generate.</param>
        /// <param name="output">Receives the generated frames.</param>
        public void Generate(
            ReadOnlySpan<SomaPose> context,
            ReadOnlySpan<SomaPose> targets,
            bool targetHasPose,
            int minTokens,
            int maxTokens,
            MotionSegment output)
        {
            var stopwatch = Stopwatch.StartNew();
            RigidTransform alignment = Encode(context, targets, targetHasPose, minTokens, maxTokens);
            session.Run(runOptions, InputNames, inputs, OutputNames, outputs);
            output.InferenceMilliseconds = stopwatch.Elapsed.TotalMilliseconds;

            Decode(math.clamp(tokenCount[0], minTokens, maxTokens), alignment, output);
            CorrectEndpoints(context[PosesPerToken - 1], targetHasPose ? targets[0] : null, output);
        }

        RigidTransform Encode(
            ReadOnlySpan<SomaPose> context,
            ReadOnlySpan<SomaPose> targets,
            bool targetHasPose,
            int minTokens,
            int maxTokens)
        {
            // Context poses fill slots 0-3. Unused target slots repeat the last target.
            for (int slot = 0; slot < Slots; slot++)
            {
                SomaPose pose = slot < PosesPerToken
                    ? context[slot]
                    : targets[math.min(slot - PosesPerToken, targets.Length - 1)];
                pose.ComputeWorld(
                    slotPositions.AsSpan(slot * Joints, Joints),
                    slotRotations.AsSpan(slot * Joints, Joints));
            }

            // Move the last context pose to the origin and turn it to face +X, like the original engine.
            const int lastContext = PosesPerToken - 1;
            int c = lastContext * Joints;
            float heading = SomaPose.HeadingFromLegs(
                slotPositions[c + SomaSkeleton.RightLeg], slotPositions[c + SomaSkeleton.LeftLeg]);
            var alignment = new RigidTransform(
                quaternion.RotateY(heading - math.PI / 2),
                new float3(slotPositions[c].x, 0, slotPositions[c].z));
            quaternion inverseAlign = math.inverse(alignment.rot);
            float3 Aligned(float3 p) => math.mul(inverseAlign, p - alignment.pos);

            for (int slot = 0; slot < Slots; slot++)
            {
                // Root velocities look at the next pose, so they are zero at the last context pose.
                int s = slot * Joints;
                int n = (slot == lastContext ? slot : math.min(slot + 1, Slots - 1)) * Joints;
                float3 hips = Aligned(slotPositions[s]);
                float3 nextHips = Aligned(slotPositions[n]);
                float angle = SomaPose.HeadingFromLegs(
                    Aligned(slotPositions[s + SomaSkeleton.RightLeg]), Aligned(slotPositions[s + SomaSkeleton.LeftLeg]));
                float nextAngle = SomaPose.HeadingFromLegs(
                    Aligned(slotPositions[n + SomaSkeleton.RightLeg]), Aligned(slotPositions[n + SomaSkeleton.LeftLeg]));
                float turn = math.atan2(math.sin(nextAngle - angle), math.cos(nextAngle - angle));

                // Root position and heading
                globalRootValues[slot * 5 + 0] = hips.x;
                globalRootValues[slot * 5 + 1] = hips.y;
                globalRootValues[slot * 5 + 2] = hips.z;
                globalRootValues[slot * 5 + 3] = math.cos(angle);
                globalRootValues[slot * 5 + 4] = math.sin(angle);

                // Turn rate, ground velocity and hip height
                localRootValues[slot * 4 + 0] = turn * SampleRate;
                localRootValues[slot * 4 + 1] = (nextHips.x - hips.x) * SampleRate;
                localRootValues[slot * 4 + 2] = (nextHips.z - hips.z) * SampleRate;
                localRootValues[slot * 4 + 3] = hips.y;

                // Joint positions from the hips' ground point, then a 6D rotation (two axes) per joint
                var ground = new float3(hips.x, 0, hips.z);
                Span<float> features = localPoses.AsSpan(slot * PoseFeatures, PoseFeatures);
                for (int j = 0; j < Joints; j++)
                {
                    if (j > 0)
                    {
                        Write(features[((j - 1) * 3)..], Aligned(slotPositions[s + j]) - ground);
                    }
                    quaternion rotation = math.mul(inverseAlign, slotRotations[s + j]);
                    int r = (Joints - 1) * 3 + j * 6;
                    Write(features[r..], math.mul(rotation, new float3(1, 0, 0)));
                    Write(features[(r + 3)..], math.mul(rotation, new float3(0, 1, 0)));
                }
            }

            // Masks: the context and the given targets count. Root velocity is unknown at the last context
            // and the last target pose.
            int lastTarget = PosesPerToken + targets.Length - 1;
            for (int slot = 0; slot < Slots; slot++)
            {
                int given = slot <= lastTarget ? 1 : 0;
                hasGlobalRootValues[slot] = given;
                hasLocalRootValues[slot] = slot == lastContext || slot == lastTarget ? 0 : given;
                hasLocalPoses[slot] = slot < PosesPerToken || targetHasPose ? given : 0;
            }
            for (int i = 0; i < allowedTokens.Length; i++)
            {
                int tokens = MinTokens + i;
                allowedTokens[i] = tokens >= minTokens && tokens <= maxTokens ? 1 : 0;
            }
            return alignment;
        }

        void Decode(int tokens, RigidTransform alignment, MotionSegment output)
        {
            int count = tokens * PosesPerToken - 2 * BoundaryFrames;
            output.FrameCount = count;
            for (int f = 0; f < count; f++)
            {
                ReadOnlySpan<float> row = motions.AsSpan((BoundaryFrames + f) * MotionFeatures, MotionFeatures);
                output.FootContacts[f] = math.saturate(new float4(row[^4], row[^3], row[^2], row[^1]));

                // The output holds the rotation of every joint in the aligned space.
                for (int j = 0; j < Joints; j++)
                {
                    ReadOnlySpan<float> r = row.Slice(MotionRotationOffset + j * 6, 6);
                    frameRotations[j] = RotationFrom6D(new float3(r[0], r[1], r[2]), new float3(r[3], r[4], r[5]));
                }

                SomaPose pose = output.Frames[f];
                pose.RootPosition = alignment.pos + math.mul(alignment.rot, new float3(row[0], row[1], row[2]));
                pose.LocalRotations[0] = math.mul(alignment.rot, frameRotations[0]);
                for (int j = 1; j < Joints; j++)
                {
                    quaternion parent = frameRotations[SomaSkeleton.Parents[j]];
                    pose.LocalRotations[j] = math.normalize(math.mul(math.inverse(parent), frameRotations[j]));
                }
            }
        }

        /// <summary>
        /// Spreads small corrections over the motion, so it starts exactly at the last context pose and,
        /// when given, ends exactly at the target pose.
        /// </summary>
        static void CorrectEndpoints(SomaPose start, SomaPose end, MotionSegment output)
        {
            int count = output.FrameCount;
            SomaPose first = output.Frames[0];
            SomaPose last = output.Frames[count - 1];
            float3 startOffset = start.RootPosition - first.RootPosition;
            float3 endOffset = end != null ? end.RootPosition - last.RootPosition : float3.zero;
            Span<quaternion> startDeltas = stackalloc quaternion[Joints];
            Span<quaternion> endDeltas = stackalloc quaternion[Joints];
            for (int j = 0; j < Joints; j++)
            {
                startDeltas[j] = math.mul(math.inverse(first.LocalRotations[j]), start.LocalRotations[j]);
                endDeltas[j] = end != null ? math.mul(math.inverse(last.LocalRotations[j]), end.LocalRotations[j]) : quaternion.identity;
            }

            for (int f = 0; f < count; f++)
            {
                float w = (float)f / (count - 1);
                SomaPose pose = output.Frames[f];
                pose.RootPosition += startOffset * (1 - w) + endOffset * w;
                for (int j = 0; j < Joints; j++)
                {
                    quaternion rotation = math.mul(pose.LocalRotations[j], math.slerp(quaternion.identity, startDeltas[j], 1 - w));
                    pose.LocalRotations[j] = math.normalize(math.mul(rotation, math.slerp(quaternion.identity, endDeltas[j], w)));
                }
            }
        }

        static void Write(Span<float> destination, float3 value)
        {
            destination[0] = value.x;
            destination[1] = value.y;
            destination[2] = value.z;
        }

        static quaternion RotationFrom6D(float3 xRaw, float3 yRaw)
        {
            float3 x = math.normalize(xRaw);
            float3 z = math.normalize(math.cross(x, yRaw));
            return new quaternion(new float3x3(x, math.cross(z, x), z));
        }
    }
